#ifndef PY32_BOARD_H
#define PY32_BOARD_H

#include <stdint.h>
#include <stdbool.h>

/**
 * py32_board — лёгкая HAL-библиотека для платы PY32F002B.
 *
 * Инкапсулирует работу с "железом": аппаратный ШИМ, системный таймер (millis)
 * и опрос пинов, чтобы логика (main.c) была чистой и переносимой.
 */

// ─── Инициализация ──────────────────────────────────────────────────────────
/**
 * Настроить базовую периферию платы:
 * - Включает тактирование GPIOA, GPIOB, TIM1
 * - Настраивает PA0 на аппаратный ШИМ TIM1_CH1 (1 кГц)
 * - Настраивает PB4 на цифровой вход (сенсор)
 * - Запускает SysTick таймер для millis()
 */
void board_init(void);


// ─── Время ──────────────────────────────────────────────────────────────────
/**
 * Получить время со старта МК (аналог millis() в Arduino)
 * @return время в миллисекундах
 */
uint32_t board_millis(void);


// ─── Периферия ──────────────────────────────────────────────────────────────
/**
 * Установить сырое значение ШИМ (TIM1_CH1)
 * @param pwm сырое значение (0..1000)
 */
void board_set_pwm_raw(uint16_t pwm);

/**
 * Прочитать состояние сенсорной кнопки на PB4
 * @return true если сенсор активен (прижат палец), иначе false
 */
bool board_read_touch(void);

/**
 * Прочитать значение АЦП (батареи)
 */
uint16_t board_read_adc(void);

/**
 * Прочитать статус зарядки (PB5)
 * @return true если идет зарядка (USB подключен)
 */
bool board_read_charge(void);

#endif /* PY32_BOARD_H */
