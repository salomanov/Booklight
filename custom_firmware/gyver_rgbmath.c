uint8_t gyver_gamma8(uint8_t val)
{
    /* AlexGyver CIE 1931 / Gamma 2.2 fast approximation */
    uint32_t v = val;
    return (uint8_t)((v * v * v + 32512UL) / 65025UL);
}

