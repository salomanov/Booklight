uint16_t gyver_gamma_pwm(uint8_t val, uint16_t out_max)
{
    if (val == 0) return 0;
    uint16_t raw_1000 = GAMMA_256_TO_1000[val];
    if (out_max == 1000) {
        return raw_1000;
    }
    uint32_t scaled = ((uint32_t)raw_1000 * out_max + 500U) / 1000U;
    if (scaled == 0 && val > 0) scaled = 1;
    return (uint16_t)scaled;
}
